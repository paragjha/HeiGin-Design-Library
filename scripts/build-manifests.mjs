#!/usr/bin/env node
// Generates source/manifests/*.json: for every component, the exact files to copy, the other
// HeiGin components it depends on, and the npm packages to install. `--check` fails on drift.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { collect, exportedNames, isClientModule, listComponents, repoRoot, summary, versionFor } from "./lib/graph.mjs";

const check = process.argv.includes("--check");
const outDir = join(repoRoot, "source/manifests");
const components = listComponents();
const byFile = new Map(components.map((c) => [c.file, c.name]));

const manifests = components.map((c) => {
  const { files, packages } = collect(c.file);
  const internal = files.filter((f) => f !== c.file && byFile.has(f)).map((f) => byFile.get(f));
  const npm = Object.fromEntries(packages.map((p) => [p, versionFor(p)]));
  return {
    name: c.name,
    category: c.category,
    entry: c.file,
    description: summary(c.file),
    exports: exportedNames(c.file).values,
    types: exportedNames(c.file).types,
    client: isClientModule(c.file),
    files: files.map((f) => `packages/ui/src/${f}`),
    styles: ["packages/ui/src/styles/tokens.css"],
    internalDependencies: internal.sort(),
    npmDependencies: npm,
    peerDependencies: Object.fromEntries(Object.entries(npm).filter(([p]) => p === "react" || p === "react-dom")),
    install: Object.keys(npm).filter((p) => p !== "react" && p !== "react-dom"),
    copyCommand: `node scripts/copy-component.mjs ${c.name} --dest <your-app>/components/heigin`,
  };
});

const index = {
  $comment: "Generated by scripts/build-manifests.mjs. Do not edit.",
  sourceRoot: "packages/ui/src",
  components: manifests.map(({ name, category, client, internalDependencies, install }) => ({ name, category, client, internalDependencies, install })),
};

const outputs = new Map([["index.json", index], ...manifests.map((m) => [`${m.name}.json`, m])]);
const serialize = (v) => `${JSON.stringify(v, null, 2)}\n`;

if (check) {
  const stale = [];
  for (const [file, value] of outputs) {
    const path = join(outDir, file);
    if (!existsSync(path) || readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== serialize(value)) stale.push(file);
  }
  const extra = existsSync(outDir) ? readdirSync(outDir).filter((f) => f.endsWith(".json") && !outputs.has(f)) : [];
  if (stale.length || extra.length) {
    console.error(`Manifests out of date: ${[...stale, ...extra].join(", ")}\nRun: npm run manifests`);
    process.exit(1);
  }
  console.log(`Checked ${manifests.length} component manifests`);
} else {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  for (const [file, value] of outputs) writeFileSync(join(outDir, file), serialize(value));
  console.log(`Wrote ${manifests.length} component manifests to source/manifests/`);
}
