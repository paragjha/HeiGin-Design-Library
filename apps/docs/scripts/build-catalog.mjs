#!/usr/bin/env node
/**
 * Writes apps/docs/src/generated/catalog.ts — the single source of truth for
 * every number the docs site advertises publicly. Overview strip, nav badges,
 * /components intro and the command palette all read from `counts`, so the
 * manifest count, token count and MCP tool count can't drift from each other
 * (that's what caused "27 primitives on the site, 30 in MCP").
 *
 * Runs at build time via vercel.json's buildCommand chain.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..", "..", "..");
const manifestDir = join(repoRoot, "source/manifests");
const mcpToolsDir = join(repoRoot, "packages/mcp/src/tools");
const tokensPath = join(repoRoot, "tokens/tokens.json");
const licensesPath = join(repoRoot, "source/licenses.json");
const outPath = join(repoRoot, "apps/docs/src/generated/catalog.ts");

function readJSON(p) {
  return JSON.parse(readFileSync(p, "utf8"));
}

function manifestEntries() {
  const licenses = readJSON(licensesPath).items;
  return readdirSync(manifestDir)
    .filter((f) => f.endsWith(".json") && f !== "index.json")
    .map((f) => {
      const m = readJSON(join(manifestDir, f));
      return {
        name: m.name,
        category: m.category,
        title: m.name.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join(" "),
        description: (m.description ?? "").replace(/\*\*([^*]+)\*\*/g, "$1").replace(/`([^`]+)`/g, "$1"),
        client: !!m.client,
        license: licenses[m.name] ?? "free",
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function countTokenLeaves(node) {
  if (!node || typeof node !== "object") return 0;
  if (typeof node.value === "string") return 1;
  let n = 0;
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$")) continue;
    n += countTokenLeaves(v);
  }
  return n;
}

function mcpToolList() {
  // Walk packages/mcp/src/tools/*.ts, pull the exported function name as the
  // tool identifier. Keeps the catalog honest against what the server exposes.
  return readdirSync(mcpToolsDir)
    .filter((f) => f.endsWith(".ts"))
    .map((f) => {
      const code = readFileSync(join(mcpToolsDir, f), "utf8");
      const m = code.match(/export\s+function\s+([A-Za-z0-9_]+)/);
      return m ? m[1].replace(/([A-Z])/g, "_$1").toLowerCase().replace(/^_/, "") : null;
    })
    .filter(Boolean)
    .sort();
}

function main() {
  const components = manifestEntries();
  const tokens = readJSON(tokensPath);
  const tokenCount = Object.entries(tokens)
    .filter(([k]) => !k.startsWith("$"))
    .reduce((n, [, group]) => n + countTokenLeaves(group), 0);
  const mcpTools = mcpToolList();

  const primitives = components.filter((c) => c.category === "ui");
  const patterns = components.filter((c) => c.category === "crm");

  const out = `// Generated by apps/docs/scripts/build-catalog.mjs. Do not edit by hand.
// Single source of truth for every public count the docs site advertises.

export interface CatalogItem {
  name: string;
  category: "ui" | "crm";
  title: string;
  description: string;
  client: boolean;
  license: "free" | "pro" | "team";
}

export const primitives: CatalogItem[] = ${JSON.stringify(primitives, null, 2)};

export const patterns: CatalogItem[] = ${JSON.stringify(patterns, null, 2)};

export const templates: CatalogItem[] = [];

export const mcpTools: string[] = ${JSON.stringify(mcpTools)};

export const counts = {
  primitives: ${primitives.length},
  patterns:   ${patterns.length},
  templates:  0,
  tokens:     ${tokenCount},
  manifests:  ${components.length},
  mcpTools:   ${mcpTools.length},
} as const;
`;

  writeFileSync(outPath, out);
  console.log(`build-catalog: wrote ${outPath} (${primitives.length} primitives, ${patterns.length} patterns, ${tokenCount} tokens, ${mcpTools.length} MCP tools)`);
}

main();
